"""Run notebooks/*.py on synthetic data and export them as read-only HTML pages (rendered_notebooks/).

Meant for the Docker builder stage of the public demo (Dockerfile, docs/hosting.md), where study data
can't exist. It refuses to run unless HE_DATA_SOURCE=synthetic, and refuses if a study file or a data
path is within reach. A notebook that fails to run gets no page (the dashboard says "not available")
and the script still exits 0, so one broken notebook can't take the demo down; --strict exits 1 instead.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK_DIR = ROOT / "notebooks"
OUT_DIR = ROOT / "rendered_notebooks"
# Same names as app.RENDERED_NOTEBOOKS (a test checks they match).
NOTEBOOKS = ["deid_oura_data_exploration", "he_trajectories_phenotypes"]
# Where the app and the notebooks look for the study file by default (data.DEFAULT_DATA_DIR, and
# "../../de-identified data" seen from notebooks/).
STUDY_DIRS = [ROOT.parent / "de-identified data", (NOTEBOOK_DIR / "../../de-identified data").resolve()]
# Any of these could point a notebook at real data, so their presence alone is a refusal.
DATA_ENV = ["HE_DATA_FILE", "HE_SYNTHETIC_FILE", "HE_MRN_MAP", "HE_CACHE_DIR", "JH_DATA_FILE", "JH_DATA_DIR"]
TIMEOUT_S = 600

BANNER = """<div style="position:sticky;top:0;z-index:100;background:#fff7ed;border-bottom:1px solid #fdba74;\
color:#7c2d12;font:14px/1.45 -apple-system,BlinkMacSystemFont,'Segoe UI',Inter,sans-serif;padding:10px 16px">
<strong>Read-only.</strong> Run on synthetic data generated by code &mdash; results are artefacts of the generator
settings, not clinical findings.
<a href="/notebooks" target="_top" style="color:#9a3412;font-weight:600;margin-left:8px">&larr; Notebooks tab</a>
<a href="/" target="_top" style="color:#9a3412;margin-left:8px">Dashboard</a>
</div>"""


def check_synthetic_only(env: dict[str, str] | None = None) -> None:
    """Raise SystemExit unless this run can only ever see synthetic data."""
    env = os.environ if env is None else env
    if env.get("HE_DATA_SOURCE", "").strip().lower() != "synthetic":
        raise SystemExit("render_notebooks: refusing to run: set HE_DATA_SOURCE=synthetic (rendered pages are public).")
    set_vars = [k for k in DATA_ENV if env.get(k)]
    if set_vars:
        raise SystemExit(f"render_notebooks: refusing to run with {', '.join(set_vars)} set: they can point at study data.")
    for folder in STUDY_DIRS:
        if folder.is_dir() and next(folder.rglob("*.rds"), None) is not None:
            raise SystemExit(f"render_notebooks: refusing to run: a study .rds file is reachable in {folder}.")


def clean_html(html: str) -> str:
    """Static page: no scripts (so no CDN calls for require.js, MathJax, Mermaid), plus the banner."""
    html = re.sub(r"<script\b[^>]*>.*?</script>", "", html, flags=re.S | re.I)
    html = re.sub(r"(<head[^>]*>)", r'\1\n<base target="_top">', html, count=1, flags=re.I)
    return re.sub(r"(<body[^>]*>)", lambda m: m.group(1) + "\n" + BANNER, html, count=1, flags=re.I)


def render(name: str) -> Path:
    import jupytext
    from nbclient import NotebookClient
    from nbconvert import HTMLExporter

    nb = jupytext.read(NOTEBOOK_DIR / f"{name}.py")
    nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
    NotebookClient(nb, timeout=TIMEOUT_S, kernel_name="python3",
                   resources={"metadata": {"path": str(NOTEBOOK_DIR)}}).execute()
    exporter = HTMLExporter(template_name="lab", embed_images=True,
                            exclude_input_prompt=True, exclude_output_prompt=True)
    html, _ = exporter.from_notebook_node(nb, resources={"metadata": {"name": name.replace("_", " ")}})
    out = OUT_DIR / f"{name}.html"
    out.write_text(clean_html(html), encoding="utf-8")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("names", nargs="*", help=f"default: all of {', '.join(NOTEBOOKS)}")
    parser.add_argument("--strict", action="store_true", help="exit 1 if any notebook fails")
    args = parser.parse_args()
    if unknown := set(args.names) - set(NOTEBOOKS):
        parser.error(f"unknown notebook(s): {', '.join(sorted(unknown))}")
    args.names = args.names or NOTEBOOKS

    check_synthetic_only()
    # The kernel inherits this environment: the in-memory synthetic cohort only.
    os.environ.update(HE_DATA_SOURCE="synthetic", HE_PUBLIC_DEMO="1")
    OUT_DIR.mkdir(exist_ok=True)
    failed = []
    for name in args.names:
        (OUT_DIR / f"{name}.html").unlink(missing_ok=True)  # no stale page if this run fails
        start = time.perf_counter()
        try:
            out = render(name)
        except Exception as exc:  # noqa: BLE001  any failure → no page, keep going
            failed.append(name)
            last = re.sub(r"\x1b\[[0-9;]*m", "", str(exc)).strip().splitlines()[-1:] or [type(exc).__name__]
            print(f"FAILED  {name} after {time.perf_counter() - start:.1f}s: {type(exc).__name__}: {last[0][:300]}")
            print(str(exc)[-3000:], file=sys.stderr)
            continue
        print(f"rendered {name} in {time.perf_counter() - start:.1f}s ({out.stat().st_size / 1e6:.2f} MB)")
    return 1 if failed and args.strict else 0


if __name__ == "__main__":
    sys.exit(main())
